def ch_gallery():
    D.h2('G. चित्रसंग्रह: प्रत्येक स्क्रीनचा स्क्रीनशॉट', 'app-gallery')
    D.p('प्रत्येक स्क्रीनशॉट चालू अ‍ॅपमधून, त्या भूमिकेने साइन इन करून घेतला आहे. संगणकावरील स्क्रीनशॉटमध्ये डावा मेनू वगळून पहिल्या नजरेत दिसणारा भाग आहे; '
        'लांब स्क्रीनच्या उरलेल्या भागासाठी अ‍ॅपमध्ये खाली स्क्रोल करा.')
    order = ['public', 'admin', 'surveyor', 'technician', 'customer', 'supplier']
    for role in order:
        ss = [s for s in B.SCREENS if s['role'] == role]
        ss.sort(key=lambda s: (s['id'], s['viewport'], s['file']))
        D.h3(f'{ROLE[role]} ({len(ss)})')
        cells = []
        for s in ss:
            path = B.SHOTS / s['file']
            from PIL import Image
            im = Image.open(path)
            if s['viewport'] == 'mobile':
                crop, px, w = (0, 0, im.width, min(im.height, 1600)), 420, 'w-phone'
            else:
                crop, px, w = ((240 if role != 'public' else 0), 0, im.width, min(im.height, 860)), 680, 'w-full'
            notes = []
            if s['viewport'] == 'mobile':
                notes.append('फोन')
            if s['loading']:
                notes.append('लोडिंगवरच राहिली: ज्ञात दोष')
            cap = f'{s["id"]} · {B.esc(s["h1"] or "—")}' + (f' ({", ".join(notes)})' if notes else '')
            cells.append(D.figure_file(gallery_key(s), path, cap, w, crop, px, 70, src_note=s['url'], inline=True))
        D.raw('<div class="gallery">' + ''.join(cells) + '</div>')


# ================================================================= inventory file

def write_inventory(doc: B.Doc):
    used = defaultdict(list)
    for s in doc.used_shots:
        used[s['file']].append(doc.figs[s['figure_key']])
    lines = ['# AIEC screen and screenshot inventory', '',
             'Generated by `documentation/manual/build_manual.py` with the Marathi user manual (`output/Application_User_Manual.pdf`).',
             'One row per screenshot: the screen, the role it was taken as, the address, the Marathi heading on it, the file, and where the manual uses it.',
             'Every screenshot is also in the manual\'s appendix gallery (section 15 G).', '',
             '| Screen | Role | View | Address | Heading (as shown) | Screenshot | Manual figures | State |', '|---|---|---|---|---|---|---|---|']
    for s in sorted(B.SCREENS, key=lambda x: (x['id'], x['role'], x['viewport'])):
        figs = ', '.join(used.get(s['file'], []) + [doc.figs.get(gallery_key(s), '')]).strip(', ')
        state = 'loading placeholder (known defect)' if s['loading'] else ('refused' if s['refused'] else ('error' if s['error'] else 'ok'))
        lines.append(f"| {s['id']} | {s['role']} | {s['viewport']} | `{s['url']}` | {s['h1'] or '—'} | `manual_assets/screenshots/{s['file']}` | {figs} | {state} |")
    lines += ['', '## Interface shots (annotated)', '']
    for k in ['ui-desktop', 'ui-mobile', 'ui-assistant', 'ui-sheet', 'acc-login', 'acc-otp', 'acc-gate', 'acc-demo', 'ui-lang-mr']:
        lines.append(f'- {k}: {doc.figs.get(k, "")}')
    (B.ROOT / 'documentation' / 'SCREEN_INVENTORY.md').write_text('\n'.join(lines) + '\n', 'utf8')
    print('wrote documentation/SCREEN_INVENTORY.md')
