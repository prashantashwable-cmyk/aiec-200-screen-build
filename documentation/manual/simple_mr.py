"""The manual in very simple Marathi, for people who are not used to apps.

Rules for this text: short sentences, everyday words, one action per step, a picture next to the step,
no web addresses or screen codes in the main text (those stay in the appendix for the office).
Button names are still the app's own words (U / L), so a reader can match them on the screen.
"""
from __future__ import annotations

import build_manual as B
import content_mr as C
from content_mr import F, L, NAV, Q, S, U

D: B.Doc


def fig(key, role, sid, cap, **kw):
    return D.figure(key, role, sid, cap, **kw)


def ifig(key, role, sid, cap, **kw):
    return D.figure(key, role, sid, cap, inline=True, **kw)


def task(title, anchor, *, why, where, need, steps, pics, things, then, wrong, remember):
    """One job, in nine simple parts."""
    D.h2(title, anchor)
    D.label('हे कशासाठी?')
    D.p(why)
    D.label('कुठे मिळेल?')
    D.p(where)
    D.label('आधी काय लागेल?')
    D.p(need)
    D.label('असे करा')
    D.steps(steps)
    D.label('चित्र पाहा')
    pics()
    D.label('स्क्रीनवरील गोष्टी')
    D.table(['तुम्हाला दिसेल', 'त्याचा अर्थ'], [[a, b] for a, b in things])
    D.label('मग काय होईल?')
    D.p(then)
    D.label('चूक झाली तर?')
    D.ul(wrong)
    D.label('लक्षात ठेवा')
    D.ul(remember)


