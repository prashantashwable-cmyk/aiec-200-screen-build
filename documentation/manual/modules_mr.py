def fig(key, role, sid, cap, **kw):
    return lambda: D.figure(key, role, sid, cap, **kw)


def figs(*fns):
    def run():
        for f in fns:
            f()
    return run


def row(*items):
    """Several figures side by side (phone-width screens)."""
    def run():
        D.fig_row([f(inline=True) for f in items])
    return run


def ifig(key, role, sid, cap, **kw):
    return lambda inline=False: D.figure(key, role, sid, cap, inline=inline, **kw)


